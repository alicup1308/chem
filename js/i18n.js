const ChemI18N = {
  get lang(){ return localStorage.getItem('cf-lang') || 'en'; },
  set lang(v){ localStorage.setItem('cf-lang', v); },
  t(key){
    const l = this.lang;
    return (I18N[l] && I18N[l][key]) || I18N.en[key] || key;
  },
  apply(l){
    if (l) this.lang = l;
    const cur = this.lang;
    document.documentElement.lang = cur;
    document.documentElement.dir = cur === 'ar' ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach(el=>{
      const k = el.getAttribute('data-i18n');
      const v = this.t(k);
      if (v) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
      el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-placeholder')));
    });
    const lb = document.getElementById('langBtn');
    if (lb) lb.textContent = cur === 'en' ? 'العربية' : 'English';
    document.title = cur === 'ar'
      ? (document.querySelector('main')?.classList.contains('table-page') ? 'الجدول الدوري — كيمفورج' : 'كيمفورج — كيمياء تفاعلية')
      : document.title;
    document.dispatchEvent(new CustomEvent('langchange', {detail:{lang:cur}}));
  },
  toggle(){ this.apply(this.lang === 'en' ? 'ar' : 'en'); }
};